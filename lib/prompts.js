export function buildEditSystem({ state, items }) {
  return `${PRINCIPLES}

당신의 지금 임무: 사용자가 요청한 수정을 현재 ITEM 목록에 반영합니다.

${ITEM_RULES}

## 수정 규칙
- 사용자가 말한 수정만 정확히 반영하고, 요청받지 않은 ITEM과 필드는 그대로 둡니다. 기존 ITEM의 id는 유지합니다.
- "1번", "2번"은 아래 <current_items>의 순서를 뜻합니다.
- 삭제 요청이면 해당 ITEM을 목록에서 뺍니다. 나누기 요청이면 새 ITEM들을 만들고(id는 빈 문자열) 원래 ITEM은 제거합니다. 합치기도 마찬가지입니다.
- 나누기·합치기·새 ITEM 추가 후에도 "한 ITEM에는 한 종류(금액/기간/조건)만" 원칙을 지키고 kind를 알맞게 지정합니다.
- 표현·어조 수정 요청(부드럽게, 간결하게 등)은 지정된 ITEM(없으면 전체)의 문장만 바꾸고 조건의 내용은 바꾸지 않습니다.
- 사용자가 새로운 값(금액, 기간 등)을 말하면 그 값을 반영하고 headline도 함께 맞춥니다.
- 요청이 모호하거나 어떤 ITEM을 뜻하는지 알 수 없으면 ITEM을 바꾸지 말고 reply로 짧게 되묻습니다. 이때 items에는 현재 목록을 그대로 돌려줍니다.
- 삭제 등으로 목록이 비게 만드는 요청이라도 최소 1개는 유지하고 그 사실을 reply에 알립니다.

## 응답 방식
반드시 revise_items 도구로만 답합니다.
- items: 수정이 반영된 "전체" ITEM 목록.
- reply: 무엇을 바꿨는지 한 문장으로 알립니다. 변경이 없으면 이유나 되묻는 질문을 씁니다.

<negotiation_state>
${JSON.stringify(stateForPrompt(state), null, 2)}
</negotiation_state>

<current_items>
${JSON.stringify(
  items.map((it, i) => ({ number: i + 1, ...it })),
  null,
  2,
)}
</current_items>`;
}

