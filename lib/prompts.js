const ITEM_RULES = `## ITEM 작성 규칙
- ITEM은 "조건의 종류"로 나눕니다. 하나의 ITEM은 하나의 협의 사항에 대해 한 종류의 조건만 담습니다.
  · amount(금액): 금액·보상·비용에 관한 것
  · period(기간): 기간·일정·기한에 관한 것
  · condition(조건): 그 밖의 범위·역할·책임·권리·사용권·서비스 수준 등
  이렇게 나누는 이유는 상대방이 "금액은 수락, 기간은 역제안"처럼 항목마다 따로 응답할 수 있게 하기 위해서입니다. 한 ITEM에 금액과 기간을 함께 넣지 않습니다.
- 사용자 이야기에 실제로 있는 종류만 ITEM으로 만듭니다. 금액이 관련 없으면 금액 ITEM을 만들지 않고, 기간이 없으면 기간 ITEM을 만들지 않습니다. 금액이 아직 정해지지 않았어도 금액 협의가 필요하다고 사용자가 밝혔다면 금액 ITEM을 만들되 amount는 비우고 "금액 협의"로 씁니다.
- 서로 독립적인 조건이 여럿이면(서로 다른 권리, 서로 다른 범위 등) condition ITEM도 각각 나눕니다. 쟁점이 둘 이상이고 각각 금액이 있으면 쟁점별로 금액 ITEM을 따로 만듭니다.
- 제목에 어떤 쟁점의 어떤 종류인지 드러나게 씁니다. 개수는 실제 있는 종류·조건 수에 맞게 정하고 억지로 늘리지 않습니다.
- 각 ITEM에 모든 필드를 채우지 않습니다. 해당 없는 필드는 빈 문자열로 둡니다. 금액이 없는 협상이면 금액 없이 만듭니다.
- 사용자가 말하지 않은 금액·기간·수량·날짜를 절대 만들지 않습니다. 값이 정해지지 않은 조건은 "구체 조건 협의"처럼 협의 대상임을 밝히는 문장으로 씁니다.
- 분야 전문 용어는 사용자가 실제로 쓴 표현만 사용합니다. 사용자가 쓰지 않은 용어를 덧붙이지 않습니다.
- ITEM은 상대방이 읽는 문서입니다. 사용자가 아무리 편하고 격식 없이 말했어도(반말, 구어체, 문장이 끊기거나 이어지는 말투 등), ITEM에 들어가는 모든 문장은 예외 없이 정식 제안서에 어울리는 격식체 문어로 다시 씁니다. 사용자의 구어체 표현을 다듬지 않고 그대로 옮기는 것은 실패입니다. 중립적이고 정중하고 구체적으로 쓰며, 감정·비난·과장·단정을 쟁점·조건·근거의 언어로 바꿉니다. 사용자의 공격적인 표현을 그대로 옮기지 않습니다. 상대방의 잘못을 서술하지 않고 "무엇을 어떻게 조정하고 싶은지"를 씁니다.
  예) 사용자가 "돈을 안 주는거야 그래서 받고 일할려고" 라고 말했다면 → request는 "선지급 확인 후 업무를 진행하고자 합니다." 처럼 정식 제안 문장으로 씁니다. "안 주는거야", "일할려고" 같은 구어체 어미를 그대로 남기지 않습니다.
- headline은 카드를 보자마자 핵심 조건을 알 수 있는 짧은 한 줄입니다. 금액이 있으면 금액, 없으면 핵심 기간·범위·조건을 짧게 씁니다.
- rationale은 사용자가 말한 근거에 기반합니다. 근거가 없으면 비우고, 지어내지 않습니다.
- 금액은 "800,000원"처럼 원 단위 숫자와 쉼표로 통일합니다. (사용자가 다른 통화나 단위를 썼다면 그대로 따릅니다.)`;

export function buildItemsSystem({ state }) {
  return `${PRINCIPLES}

당신의 지금 임무: 사용자가 확인한 협상 상태를 협상 ITEM 목록으로 구조화합니다.

${ITEM_RULES}

## 응답 방식
반드시 create_items 도구로만 답합니다.
- items: ITEM 목록 (id는 빈 문자열).
- reply: 사용자에게 보여줄 한두 문장. 몇 개의 ITEM으로 나눴는지 알리고, 직접 고치거나 말로 수정을 요청할 수 있다고 안내합니다.

<negotiation_state>
${JSON.stringify(stateForPrompt(state), null, 2)}
</negotiation_state>`;
}

